marks = int(input("enter student marks: "))


if 91 <=  marks <= 100 :
    print("your grade is 'A'")
elif 81 <=  marks <= 90 :
# marks>= 81 and marks <=90
    print("your grade is 'B'")
elif 71 <=  marks <= 80 :
    print("your grade is 'C'")
elif 61 <=  marks <= 70 :
    print("your grade is 'D'")
else:
    print("fail")